/**
 * selftest/fixtures/templates/integrator/integrator-host-half-template.ts —— 批量集成方 host half 的 TS 源模板。
 *
 * 生成物落在夹具包的 src/index.ts，再由 esbuild 打成 lib/index.js（Node ESM，外部依赖走 profile 的 node_modules）。
 * 内容三件事（每件都对应 #258/#266 的一条验收）：
 *   1. createMultiHostUpdate：按身份单源接线批量电话 + 每个目标的单插件电话（批量面板/中枢靠它）；
 *   2. HTTP 桥：DSH 没有内建 host↔client 电话通道，client half 用同源 fetch 走这座桥；
 *   3. 构建标记电话：把 host 侧版本 + 行为字段回报给 client（重启后 UI 上能看出 host 代码真的换了）。
 */
import type { FixtureBuildTags, FixtureSlot, FixtureVariantEffect } from '../../identity/fixture-slots.ts'
import { FIXTURE_INSTALL_TIMEOUT_ENV, FIXTURE_REGISTRY_ENV, fixtureBridgeRouteOf, fixtureBuildTagPhoneOf } from '../../identity/fixture-slots.ts'

/** 集成方 host half 的渲染入参。 */
export interface IntegratorHostHalfInputs {
  readonly slot: FixtureSlot
  /** 只是让调用方把版本显式带进来（可见变化在 buildTags 里）；渲染不直接用它。 */
  readonly version: string
  readonly buildTags: FixtureBuildTags
  /** 版本变体效果（缺省 = T1 单面板效果）。 */
  readonly effect?: FixtureVariantEffect
}

/** 单引号包一层（夹具身份值都是简单字面量，不含引号/反斜杠；不引第三方工具）。 */
function quote(value: string): string {
  return "'" + value + "'"
}

/** 渲染集成方 host half 的 TypeScript 源码。 */
export function renderIntegratorHostHalf(inputs: IntegratorHostHalfInputs): string {
  const { slot, buildTags } = inputs
  const batch = slot.batch
  if (slot.role !== 'integrator' || !batch || !slot.selfTargetPrefix) {
    throw new Error('[fixtures] 席位 ' + slot.key + ' 不是集成方，不能渲染集成方 host half')
  }
  const effect = inputs.effect ?? { ui: 'single' as const, titleSuffix: '', hubDock: false, hostBehavior: null, seatLine: '' }
  const targetLines = batch.targets
    .map(
      (target) =>
        '      { key: ' +
        quote(target.key) +
        ', title: ' +
        quote(target.title) +
        ', packageName: ' +
        quote(target.packageName) +
        ', prefix: ' +
        quote(target.prefix) +
        ' },',
    )
    .join('\n')
  const targetKeys = quote(batch.targets.map((target) => target.key).join('/'))
  const behaviorLiteral = effect.hostBehavior === null ? 'null' : quote(effect.hostBehavior)
  return [
    '// [TEST ONLY] 夹具 host half（#266 生成产物，勿手改；源模板 = selftest/fixtures/templates/integrator）',
    "import { createMultiHostUpdate } from 'dsh-plugin-update/batch'",
    // [TEST ONLY] #284 等效宿主注入块：只读 Node 内建，不引第三方依赖。
    "import { spawn as spawnEquivalentHost } from 'node:child_process'",
    "import { existsSync as existsEquivalentHostPath, mkdirSync as mkdirEquivalentHostDir, writeFileSync as writeEquivalentHostFile } from 'node:fs'",
    "import { join as joinEquivalentHostPath } from 'node:path'",
    '',
    '/** 等效宿主注入开关：只有 selftest 场景会设置；未设置时下面整块不生效（旧场景零漂移）。 */',
    "export const EQUIVALENT_HOST_ENV = 'DSH_SELFTEST_EQUIVALENT_HOST'",
    '/** 正在执行的这份宿主代码由哪个夹具版本构建而来（等效集成方注入 runningVersion 的真实值）。 */',
    'export const EQUIVALENT_RUNNING_VERSION = ' + quote(inputs.version),
    '',
    'export const name = ' + quote(slot.packageName),
    "export const inject = ['webServer']",
    'export const BUILD_TAG = ' + quote(buildTags.hostTag),
    'export const ROUTE = ' + quote(fixtureBridgeRouteOf(slot)),
    'const BUILD_TAG_PHONE = ' + quote(fixtureBuildTagPhoneOf(slot)),
    // #266 场景 b 的「host 行为变化」机器可读证据：变体版回包多一个 behavior 字段（基版 null）。
    'export const HOST_BEHAVIOR = ' + behaviorLiteral,
    '// 批量席位声明（变体版的 host 侧也能自证：我这一席负责哪些目标）。',
    'export const TARGET_KEYS = ' + targetKeys,
    '',
    'type Json = Record<string, unknown>',
'type PhoneHandler = (args?: Json) => Promise<unknown>',
    '',
    '// ---------------------------------------------------------------------------------------------------',
    '// #284 等效宿主注入（[TEST ONLY]，边界见 docs 与 run.json 的 equivalentHost 字段）',
    '// 文档化入口：createMultiHostUpdate 的 deps.readerOverrides（README.md:527/:564/:600）；',
    '// 未设 DSH_SELFTEST_EQUIVALENT_HOST 时这些函数全都不被调用，宿主行为与旧场景逐字节一致。',
    '// ---------------------------------------------------------------------------------------------------',
    'interface EquivalentHostSpec {',
    '  kind?: string',
    '  rawDir?: string',
    '  profileDir?: string',
    '  profileName?: string',
    '  homeDir?: string',
    '  /** 真 CLI 实际使用的 profile 名（G8 的产品可见名是 desktop，但 dsh web 不许用这个名字起宿主）。 */',
    '  cliProfileName?: string',
    '  cliExe?: string',
    '  cliJs?: string',
    '  delayMs?: number',
    '  note?: string',
    '}',
    '',
    'function equivalentHostSpecOf(): EquivalentHostSpec | null {',
    '  const raw = process.env[EQUIVALENT_HOST_ENV]',
    '  if (typeof raw !== "string" || raw.trim() === "") return null',
    '  try {',
    '    const parsed = JSON.parse(raw) as EquivalentHostSpec | null',
    '    return parsed && typeof parsed === "object" ? parsed : null',
    '  } catch (error) {',
    '    return null',
    '  }',
    '}',
    '',
    'let equivalentHostCaptureSeq = 0',
    '',
    '/** 把等效宿主的每一次安装调用原文落到 raw 目录（场景会拷贝进证据包；写失败不影响产品路径）。 */',
    'function writeEquivalentHostCapture(spec: EquivalentHostSpec, payload: Json): void {',
    '  if (typeof spec.rawDir !== "string" || spec.rawDir === "") return',
    '  try {',
    '    mkdirEquivalentHostDir(spec.rawDir, { recursive: true })',
    '    equivalentHostCaptureSeq += 1',
    '    const file = joinEquivalentHostPath(spec.rawDir, "equivalent-host-" + String(equivalentHostCaptureSeq).padStart(2, "0") + ".json")',
    '    writeEquivalentHostFile(file, JSON.stringify(payload, null, 2))',
    '  } catch (error) {',
    '    // 证据写失败由场景按缺失另记，不影响产品路径',
    '  }',
    '}',
    '',
    'function equivalentHostDelay(ms: number): Promise<void> {',
    '  return new Promise((resolve) => setTimeout(resolve, ms))',
    '}',
    '',
    '/** 载体 CLI 的 argv：与执行器 spawn 口径一致（--expose-internals + cli.js + plugin --profile <真实名> ...）。 */',
    'function equivalentHostCliInvocation(spec: EquivalentHostSpec, pluginArgs: readonly string[]): { exe: string; argv: string[] } {',
    '  const exe = spec.cliExe || process.env["DSH_SELFTEST_DESKTOP_EXE"] || "D:\\DeepseekHarness\\DeepSeek Harness.exe"',
    '  const cliJs = spec.cliJs || process.env["DSH_SELFTEST_DESKTOP_CLI_JS"] || ""',
    '  const profileName = spec.cliProfileName || spec.profileName || ""',
    '  return { exe, argv: ["--expose-internals", cliJs, "plugin", "--profile", profileName, ...pluginArgs] }',
    '}',
    '',
    '/** 真跑一次载体 CLI 安装，返回退出码与输出原文（等效宿主的「真装」就靠它，不伪造结果）。 */',
    'function runEquivalentHostCli(spec: EquivalentHostSpec, pluginArgs: readonly string[]): Promise<{ exitCode: number; output: string }> {',
    '  const invocation = equivalentHostCliInvocation(spec, pluginArgs)',
    '  return new Promise((resolve) => {',
    '    let stdout = ""',
    '    let stderr = ""',
    '    let settled = false',
    '    const child = spawnEquivalentHost(invocation.exe, invocation.argv, { cwd: spec.profileDir, env: process.env, windowsHide: true })',
    '    const finish = (exitCode: number, extra: Json): void => {',
    '      if (settled) return',
    '      settled = true',
    '      writeEquivalentHostCapture(spec, { phase: "cli", exe: invocation.exe, argv: invocation.argv, cwd: spec.profileDir, exitCode, stdout: stdout.slice(-65536), stderr: stderr.slice(-65536), ...extra })',
    '      resolve({ exitCode, output: (stdout + stderr).trim() })',
    '    }',
    '    child.stdout.on("data", (chunk: unknown) => { stdout += String(chunk) })',
    '    child.stderr.on("data", (chunk: unknown) => { stderr += String(chunk) })',
    '    child.on("error", (error: unknown) => { finish(1, { spawnError: String((error as any)?.message ?? error) }) })',
    '    child.on("close", (code: number | null) => { finish(typeof code === "number" ? code : 1, {}) })',
    '  })',
    '}',
    '',
    '/** 出口一的等效 desktopPnpm 服务：runPlugin(args, dir, signal?) → { done: Promise<{exitCode}> }。',
    ' *  真机语义：无 terminate 方法（第三方宿主如实不给取消能力）；args 由产品 installRecipe 拼出，',
    ' *  这里原样交给载体 CLI。profileDir/.equiv-hang 存在时返回永不完结的 done（用来验证超时诚实文案）。',
    ' */',
    'function equivalentRunPlugin(spec: EquivalentHostSpec) {',
    '  return (pluginArgs: string[], targetDir: string, _signal?: unknown) => {',
    '    const startedAt = new Date().toISOString()',
    '    const hangFile = joinEquivalentHostPath(targetDir, ".equiv-hang")',
    '    if (existsEquivalentHostPath(hangFile)) {',
    '      writeEquivalentHostCapture(spec, { phase: "runPlugin", mode: "hang-no-terminate", args: [...pluginArgs], cwd: targetDir, startedAt })',
    '      return { done: new Promise<{ exitCode: number }>(() => {}), stdout: null, stderr: null }',
    '    }',
    '    const invocation = equivalentHostCliInvocation(spec, pluginArgs)',
    '    let stdout = ""',
    '    let stderr = ""',
    '    let settled = false',
    '    const child = spawnEquivalentHost(invocation.exe, invocation.argv, { cwd: targetDir, env: process.env, windowsHide: true })',
    '    child.stdout.on("data", (chunk: unknown) => { stdout += String(chunk) })',
    '    child.stderr.on("data", (chunk: unknown) => { stderr += String(chunk) })',
    '    const done = new Promise<{ exitCode: number }>((resolve) => {',
    '      const finish = (exitCode: number, extra: Json): void => {',
    '        if (settled) return',
    '        settled = true',
    '        writeEquivalentHostCapture(spec, { phase: "runPlugin", mode: "real-cli", exe: invocation.exe, argv: invocation.argv, cwd: targetDir, startedAt, finishedAt: new Date().toISOString(), exitCode, stdout: stdout.slice(-65536), stderr: stderr.slice(-65536), ...extra })',
    '        resolve({ exitCode })',
    '      }',
    '      child.on("error", (error: unknown) => { finish(1, { spawnError: String((error as any)?.message ?? error) }) })',
    '      child.on("close", (code: number | null) => { finish(typeof code === "number" ? code : 1, {}) })',
    '    })',
    '    return { done, stdout: child.stdout, stderr: child.stderr }',
    '  }',
    '}',
    '',
    '/** 出口二的等效 pluginManager：故意不给 cancelInstall（G8 要验证「未提供取消能力」）。',
    ' *  installBundle 先等 delayMs 再真 spawn 载体 CLI 落盘——迟到的成功就是「可能仍在后台继续」的证据。',
    ' */',
    'function equivalentPluginManager(spec: EquivalentHostSpec): Record<string, unknown> {',
    '  const delayMs = typeof spec.delayMs === "number" && spec.delayMs > 0 ? spec.delayMs : 5000',
    '  return {',
    '    async installBundle(packageSpec: string, options?: Json) {',
    '      const requestId = options && typeof options["requestId"] === "string" ? String(options["requestId"]) : null',
    '      writeEquivalentHostCapture(spec, { phase: "installBundle.request", packageSpec, options: options ?? null, requestId, delayMs, at: new Date().toISOString() })',
    '      await equivalentHostDelay(delayMs)',
    '      const installArgs: string[] = ["add", packageSpec]',
    '      if (options && typeof options["registry"] === "string" && String(options["registry"]) !== "") installArgs.push("--registry=" + String(options["registry"]))',
    '      const result = await runEquivalentHostCli(spec, installArgs)',
    '      writeEquivalentHostCapture(spec, { phase: "installBundle.result", packageSpec, requestId, application: "applied", exitCode: result.exitCode })',
    '      return { application: "applied", packageResult: { exitCode: result.exitCode, output: result.output } }',
    '    },',
    '    async removeBundle(name: string) {',
    '      writeEquivalentHostCapture(spec, { phase: "removeBundle", name })',
    '      return { application: "applied" }',
    '    },',
    '    async listBundles() { return [] },',
    '    async setBundleEnabled() { return undefined },',
    '  }',
    '}',
    '',
    '/** 按 kind 组装 readerOverrides（全部字段都是 README 记录的集成方入口，不是产品内部后门）。 */',
    'function equivalentHostOverridesOf(spec: EquivalentHostSpec): Json | null {',
    '  const profileName = typeof spec.profileName === "string" ? spec.profileName : ""',
    '  const profileDir = typeof spec.profileDir === "string" ? spec.profileDir : ""',
    '  const homeDir = typeof spec.homeDir === "string" ? spec.homeDir : ""',
    '  if (spec.kind === "desktop") {',
    '    // 出口一：真实服务形状 = desktopProfiles.current + desktopPnpm.runPlugin；environmentKind 显式声明（README.md:527）',
    '    return {',
    '      environmentKind: "desktop",',
    '      profileName,',
    '      profileDir,',
    '      homeDir,',
    '      desktopProfiles: { current: { name: profileName, dir: profileDir } },',
    '      desktopPnpm: { runPlugin: equivalentRunPlugin(spec) },',
    '    }',
    '  }',
    '  if (spec.kind === "desktop-manager") {',
    '    // 出口二：真实服务形状 = ctx.pluginManager；故意没有 cancelInstall（能力缺失就是被测点）',
    '    return {',
    '      environmentKind: "desktop-manager",',
    '      profileName: profileName || "desktop",',
    '      profileDir,',
    '      homeDir,',
    '      pluginManager: equivalentPluginManager(spec),',
    '      // 官方桌面宿主的运行版本来自已加载代码（不是磁盘 package.json）；等效宿主同样报当前加载的 host half 版本。',
    '      // 缺了它 #245 的失败结算会拿磁盘版冒充运行版，宿主仍跑旧版时面板会宣称「已是最新」。',
    '      runningVersion: EQUIVALENT_RUNNING_VERSION,',
    '    }',
    '  }',
    '  if (spec.kind === "reader-version") {',
    '    // I4：只注入「运行版」这一个文档化字段；环境仍由真实宿主探测（不覆盖 environmentKind）',
    '    return { runningVersion: EQUIVALENT_RUNNING_VERSION, profileName, profileDir, homeDir }',
    '  }',
    '  return null',
    '}',
    '',
    'function readJsonBody(req: any): Promise<unknown> {',
    '  return new Promise((resolve, reject) => {',
    "    let text = ''",
    "    req.on('data', (chunk: unknown) => { text += String(chunk) })",
    "    req.on('end', () => { try { resolve(text ? JSON.parse(text) : null) } catch (error) { reject(error) } })",
    "    req.on('error', (error: unknown) => { reject(error) })",
    '  })',
    '}',
    '',
    'function writeJson(res: any, status: number, body: Json): void {',
    '  res.statusCode = status',
    "  res.setHeader('content-type', 'application/json; charset=utf-8')",
    '  res.end(JSON.stringify(body))',
    '}',
    '',
    'function registryUrlOf(config: Json): string | undefined {',
    '  const configured = (config as { registryUrl?: unknown }).registryUrl',
    "  if (typeof configured === 'string' && configured.length > 0) return configured",
    '  const fromEnv = process.env[' + quote(FIXTURE_REGISTRY_ENV) + ']',
    "  return typeof fromEnv === 'string' && fromEnv.length > 0 ? fromEnv : undefined",
    '}',
    '',
    '/** 安装时限（毫秒）：显式配置优先，其次环境变量；非正数/非数字一律不传（产品缺省接管）。 */',
    'function installTimeoutMsOf(config: Json): number | undefined {',
    '  const configured = (config as { installTimeoutMs?: unknown }).installTimeoutMs',
    "  if (typeof configured === 'number' && Number.isFinite(configured) && configured > 0) return configured",
    '  const fromEnv = Number(process.env[' + quote(FIXTURE_INSTALL_TIMEOUT_ENV) + '])',
    '  return Number.isFinite(fromEnv) && fromEnv > 0 ? fromEnv : undefined',
    '}',
    '',
    'export function apply(ctx: any, config: Json = {}): void {',
    '  const registryUrl = registryUrlOf(config)',
    '  const installTimeoutMs = installTimeoutMsOf(config)',
    '  const deps: Json = { ctx, logCtx: null }',
    '  const depsConfig: Json = {}',
    "  if (registryUrl) depsConfig['registryUrl'] = registryUrl",
    "  if (installTimeoutMs !== undefined) depsConfig['installTimeoutMs'] = installTimeoutMs",
    '  if (Object.keys(depsConfig).length > 0) deps["config"] = depsConfig',
    '  // #284 等效宿主注入：见上方 equivalentHostOverridesOf 的边界说明。',
    '  const equivalentHost = equivalentHostSpecOf()',
    '  if (equivalentHost) {',
    '    const overrides = equivalentHostOverridesOf(equivalentHost)',
    '    if (overrides) deps["readerOverrides"] = overrides',
    '    writeEquivalentHostCapture(equivalentHost, {',
    '      phase: "apply",',
    '      kind: equivalentHost.kind ?? null,',
    '      profileName: equivalentHost.profileName ?? null,',
    '      profileDir: equivalentHost.profileDir ?? null,',
    '      homeDir: equivalentHost.homeDir ?? null,',
    '      runningVersion: EQUIVALENT_RUNNING_VERSION,',
    '      entry: "createMultiHostUpdate deps.readerOverrides（README.md:527/:564/:600 的集成方入口）",',
    '      note: equivalentHost.note ?? null,',
    '    })',
    '    writeEquivalentHostCapture(equivalentHost, { phase: "apply-summary", kind: equivalentHost.kind ?? null, routedBy: "readerOverrides.environmentKind（显式覆盖）" })',
    '  }',
    '  const multi = createMultiHostUpdate(deps as any, {',
    '    prefix: ' + quote(batch.prefix) + ',',
    '    selfKey: ' + quote(batch.selfKey) + ',',
    '    selfOrder: ' + quote(batch.selfOrder) + ',',
    '    drain: false,',
    ...(effect.batchHub === undefined ? [] : ['    hub: ' + (effect.batchHub ? 'true' : 'false') + ',']),
    '    targets: [',
    targetLines,
    '    ],',
    '  })',
    '  const handlers: Record<string, PhoneHandler> = {}',
    '  for (const phone of Object.keys(multi.handlers)) {',
    '    handlers[phone] = multi.handlers[phone] as PhoneHandler',
    '  }',
    '  handlers[BUILD_TAG_PHONE] = async () => ({',
    '    buildTag: BUILD_TAG,',
    '    role: ' + quote(slot.role) + ',',
    '    packageName: name,',
    '    behavior: HOST_BEHAVIOR,',
    '    targetKeys: TARGET_KEYS,',
    '  })',
    '  const bridge = async (req: any, res: any): Promise<void> => {',
    "    if (req.method !== 'POST') { writeJson(res, 405, { ok: false, error: 'method-not-allowed' }); return }",
    '    let body: Json | null = null',
    "    try { body = (await readJsonBody(req)) as Json | null } catch (error) { writeJson(res, 400, { ok: false, error: 'bad-json' }); return }",
    "    const phone = body && typeof body['phone'] === 'string' ? String(body['phone']) : ''",
    '    const handler = handlers[phone]',
    "    if (typeof handler !== 'function') { writeJson(res, 404, { ok: false, error: 'unknown-phone' }); return }",
    "    const args = body && typeof body['args'] === 'object' && body['args'] !== null ? (body['args'] as Json) : {}",
    '    try { writeJson(res, 200, { ok: true, reply: await handler(args) }) }',
    '    catch (error) { writeJson(res, 200, { ok: false, error: String((error as any)?.message ?? error) }) }',
    '  }',
    "  ctx.effect(() => ctx.webServer.register({ kind: 'prefix', path: ROUTE, handler: bridge }), " + quote(slot.packageName + ': phone bridge') + ')',
    '}',
    '',
  ].join('\n')
}
