/**
 * selftest/target-scaffold/scaffold-target-package.ts —— 规约 → 可发布包目录（生成层）。
 *
 * 纯与不纯分开：
 * - 纯：`buildTargetPackageManifest` / `buildTargetPackageFiles` 是纯函数
 *   （同样输入 → 同样字节：键排序、LF、末尾恰好一个换行；可单测，不碰磁盘）。
 * - 不纯：`writeTargetPackageFiles` 是薄 IO（只写传进来的表，不读 registry、不调宿主）。
 *
 * 模式：Builder（调用方先 `build…` 拿到 FileMap，检查完再 `write…` 落盘；两步之间可断言）。
 * 注意：生成的 `index.js` 故意是最小 JS——它是“靶子包”的运行时，不是本仓源码；
 * 本仓源码（本文件）是 TS，满足“新增一律 TS”。
 */

import type { FixtureTargetSpec, FixtureVersion } from '../target-definition/target-spec.js'

/** 文件表：相对路径 → 文件字节（LF）。键已排序，写盘时按此顺序写，保证确定性。 */
export type FileMap = Readonly<Record<string, string>>

function withTrailingNewline(text: string): string {
  return text.replace(/\r\n/g, '\n').replace(/\s+$/, '') + '\n'
}

/**
 * 纯：生成靶子包的 package.json 字节。
 * 字段取最小可安装集：name/version/description/private=false 故意不写 private
 * ——C 档真发时必须可发布；B 档本地闭环只读这个 JSON，不发布。
 * 不带 `dsh` 关键字、不带 `dsh.plugin` 入口：靶子不是真插件，防被误装（见 README 对抗表）。
 */
export function buildTargetPackageManifest(spec: FixtureTargetSpec, version: FixtureVersion): string {
  const manifest = {
    name: spec.name,
    version,
    description: spec.description,
    license: 'MIT',
    type: 'module',
    main: 'index.js',
  }
  return withTrailingNewline(JSON.stringify(manifest, null, 2))
}

/** 纯：生成靶子包的全部文件（package.json + 最小运行时 + 说明）。 */
export function buildTargetPackageFiles(spec: FixtureTargetSpec, version: FixtureVersion): FileMap {
  const indexJs = withTrailingNewline(
    `// TEST ONLY fixture (generated by selftest/target-scaffold, do not edit by hand).\n// Stable runtime marker: the harness asserts on VERSION, nothing else.\nexport const TARGET_NAME = ${JSON.stringify(spec.name)};\nexport const VERSION = ${JSON.stringify(version)};\n`,
  )
  const readme = withTrailingNewline(
    `# ${spec.name}\n\nTEST ONLY selftest target for dsh-plugin-update (slot ${spec.slot}, version ${version}). Not a real plugin; do not install manually.\n`,
  )
  const files: Record<string, string> = {
    'README.md': readme,
    'index.js': indexJs,
    'package.json': buildTargetPackageManifest(spec, version),
  }
  const ordered: Record<string, string> = {}
  for (const key of Object.keys(files).sort()) ordered[key] = files[key]
  return ordered
}

/** 薄 IO：把 FileMap 原样写进目录（先建目录；不做网络、不调宿主、不改名）。 */
export async function writeTargetPackageFiles(rootDir: string, files: FileMap): Promise<void> {
  const { mkdir, writeFile } = await import('node:fs/promises')
  const { resolve, dirname, sep } = await import('node:path')
  const root = resolve(rootDir)
  await mkdir(root, { recursive: true })
  for (const [relativePath, content] of Object.entries(files)) {
    if (relativePath.includes('\0') || relativePath.startsWith('/') || relativePath.includes('..' + sep)) {
      throw new Error(`[selftest] unsafe relative path: ${relativePath}`)
    }
    const full = resolve(root, relativePath)
    if (dirname(full) !== root) {
      // B 档只允许顶层三个文件；子目录形态留给 C 档（需要时再放开，不 silent 支持）。
      throw new Error(`[selftest] nested path not allowed in B: ${relativePath}`)
    }
    await writeFile(full, content)
  }
}
